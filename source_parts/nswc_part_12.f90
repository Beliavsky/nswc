SUBROUTINE DRNOR (IX, A, N, IERR)
IMPLICIT NONE
INTENT(IN) N
INTEGER IERR, IX, N
INTEGER I, M, MAX
!-----------------------------------------------------------------------
!                 NORMAL RANDOM NUMBER GENERATOR
!-----------------------------------------------------------------------
DOUBLE PRECISION A(N)
DOUBLE PRECISION R, S, U, V, T(2)
!---------------------
DATA MAX /2147483647/
!---------------------
IF (N .LE. 0) GO TO 100
