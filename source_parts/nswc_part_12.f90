!        IT IS REQUIRED THAT A AND B NOT BE LESS
!        THAN 0.25 SO THAT X1 + X2 IS NONZERO.
!
   X(I) = X1/(X1 + X2)
!
END DO
RETURN
!
!                      ERROR RETURN
!
100 IERR = 1
RETURN
110 IERR = 2
RETURN
120 IERR = 3
RETURN
END SUBROUTINE RBETA

