SUBROUTINE TQLRT0 (N,D,E2,IERR)
IMPLICIT NONE
INTEGER NHALF, NTOP
REAL DHOLD
INTEGER IK, K, NCMPLX, NM, NPP
REAL CNV
!
INTEGER I          ,J          ,L          ,M          , &
&N          ,II         ,L1         ,MML        , &
&IERR
REAL D(N)       ,E2(N)
REAL B          ,C          ,F          ,G          , &
&H          ,P          ,R          ,S          , &
&MACHEP
!
COMMON /CBLKT/  NPP        ,K          ,MACHEP     ,CNV        , &
&NM         ,NCMPLX     ,IK
!
!
!     THIS SUBROUTINE IS A MODIFICATION OF THE EISPACK SUBROUTINE
!     TQLRAT. THE SUBROUTINE FINDS THE EIGENVALUES OF A SYMMETRIC
!     TRIDIAGONAL MATRIX BY THE RATIONAL QL METHOD.
!
!     ON INPUT-
!
!        N IS THE ORDER OF THE MATRIX,
!
!        D CONTAINS THE DIAGONAL ELEMENTS OF THE INPUT MATRIX,
!
!        E2 CONTAINS THE                SUBDIAGONAL ELEMENTS OF THE
!          INPUT MATRIX IN ITS LAST N-1 POSITIONS.  E2(1) IS ARBITRARY.
!
!      ON OUTPUT-
!
!        D CONTAINS THE EIGENVALUES IN ASCENDING ORDER.  IF AN
!          ERROR EXIT IS MADE, THE EIGENVALUES ARE CORRECT AND
!          ORDERED FOR INDICES 1,2,...IERR-1, BUT MAY NOT BE
!          THE SMALLEST EIGENVALUES,
!
!        E2 HAS BEEN DESTROYED,
!
!        IERR IS SET TO
!          ZERO       FOR NORMAL RETURN,
!          J          IF THE J-TH EIGENVALUE HAS NOT BEEN
!                     DETERMINED AFTER 30 ITERATIONS.
!
!
!     ********** MACHEP IS A MACHINE DEPENDENT PARAMETER SPECIFYING
!                THE RELATIVE PRECISION OF FLOATING POINT ARITHMETIC.
!
!                **********
!
IERR = 0
IF (N .EQ. 1) GO TO 150
!
DO I=2,N
   E2(I-1) = E2(I)*E2(I)
END DO
!
F = 0.0
B = 0.0
E2(N) = 0.0
!
DO L=1,N
   J = 0
   H = MACHEP*(ABS(D(L))+SQRT(E2(L)))
   IF (B .GT. H) GO TO  20
   B = H
   C = B*B
!
!     ********** LOOK FOR SMALL SQUARED SUB-DIAGONAL ELEMENT **********
!
20 do 30 M = L,N
      IF (E2(M) .LE. C) GO TO  40
!
!     ********** E2(N) IS ALWAYS ZERO, SO THERE IS NO EXIT
!                THROUGH THE BOTTOM OF THE LOOP **********
!
30 CONTINUE
!
40 IF (M .EQ. L) GO TO  80
50 IF (J .EQ. 30) GO TO 140
   J = J+1
!
!     ********** FORM SHIFT **********
!
   L1 = L+1
   S = SQRT(E2(L))
   G = D(L)
   P = (D(L1)-G)/(2.0*S)
   R = SQRT(P*P+1.0)
   D(L) = S/(P+SIGN(R,P))
   H = G-D(L)
!
   DO I=L1,N
      D(I) = D(I)-H
   END DO
!
   F = F+H
!
!     ********** RATIONAL QL TRANSFORMATION **********
!
   G = D(M)
   IF (G .EQ. 0.0) G = B
   H = G
   S = 0.0
   MML = M-L
!
!     ********** FOR I=M-1 STEP -1 UNTIL L DO -- **********
!
   DO II=1,MML
      I = M-II
      P = G*H
      R = P+E2(I)
      E2(I+1) = S*R
      S = E2(I)/R
      D(I+1) = H+S*(H+D(I))
      G = D(I)-E2(I)/G
      IF (G .EQ. 0.0) G = B
      H = G*P/R
   END DO
!
   E2(L) = S*G
   D(L) = H
!
!     ********** GUARD AGAINST UNDERFLOWED H **********
!
   IF (H .EQ. 0.0) GO TO  80
   IF (ABS(E2(L)) .LE. ABS(C/H)) GO TO  80
   E2(L) = H*E2(L)
   IF (E2(L) .NE. 0.0) GO TO  50
80 P = D(L)+F
!
!     ********** ORDER EIGENVALUES **********
!
   IF (L .EQ. 1) GO TO 100
!
!     ********** FOR I=L STEP -1 UNTIL 2 DO -- **********
!
   DO II=2,L
      I = L+2-II
      IF (P .GE. D(I-1)) GO TO 110
      D(I) = D(I-1)
   END DO
!
100 I = 1
110 D(I) = P
END DO
!
IF (ABS(D(N)) .GE. ABS(D(1))) GO TO 150
NHALF = N/2
DO I=1,NHALF
   NTOP = N-I
   DHOLD = D(I)
   D(I) = D(NTOP+1)
   D(NTOP+1) = DHOLD
END DO
GO TO 150
!
!     ********** SET ERROR -- NO CONVERGENCE TO AN
!                EIGENVALUE AFTER 30 ITERATIONS **********
!
140 IERR = L
150 RETURN
END SUBROUTINE TQLRT0

