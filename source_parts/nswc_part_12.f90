!                  OBTAIN THE FIRST M VARIATES
!
DO I = 1,M,2
   U = A(I)
   V = A(I + 1)
   R = U*U + V*V
   S = DSQRT(-2.D0*DLOG(R)/R)
   A(I) = S*U
   A(I + 1) = S*V
