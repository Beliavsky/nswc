SUBROUTINE RNOR (IX, A, N, IERR)
IMPLICIT NONE
INTENT(IN) N
INTEGER IERR, IX, N
INTEGER I, M, MAX
REAL R, S, U, V
!-----------------------------------------------------------------------
!                 NORMAL RANDOM NUMBER GENERATOR
!-----------------------------------------------------------------------
REAL A(N), T(2)
!---------------------
DATA MAX /2147483647/
!---------------------
IF (N .LE. 0) GO TO 100
IF (IX .LE. 0 .OR. IX .GE. MAX) GO TO 110
IERR = 0
!
IF (N .EQ. 1) GO TO 20
M = N/2
CALL RCIR1 (M, IX, A(1), 2, A(2), 2, IERR)
M = M + M
!
!                  OBTAIN THE FIRST M VARIATES
!
DO I = 1,M,2
   U = A(I)
   V = A(I + 1)
   R = U*U + V*V
   S = SQRT(-2.0*ALOG(R)/R)
   A(I) = S*U
