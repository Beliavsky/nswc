"""Build and check the module-only FORD reference site."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
from fortran_procedures import procedure_spans
ROOT=Path(__file__).resolve().parents[1]
STAGE=ROOT/'reports/ford-input'
OUTPUT=ROOT/'reports/ford-site'
OWNER='.nswc-ford-output'


def check_site():
    source=(ROOT/'nswc_mod.f90').read_bytes()
    from ford_documentation import transform
    if transform(source.decode('ascii'))!=source.decode('ascii'):
        raise ValueError('FORD prologues are stale; run tools/regenerate_sources.py')
    if (STAGE/'nswc_mod.f90').read_bytes()!=source:
        raise ValueError('Staged FORD source differs from the current module')
    expected={n.lower() for n,_,_ in procedure_spans(source.decode('ascii'))}
    if len(expected)!=1062:raise ValueError('Expected the complete 1,062-procedure module')
    actual={p.stem for p in (OUTPUT/'proc').glob('*.html')}
    if actual!=expected:raise ValueError('FORD procedure inventory differs: '+str(sorted(actual^expected)))
    if not (OUTPUT/'index.html').is_file() or not (OUTPUT/'module/nswc_mod.html').is_file():
        raise ValueError('FORD front page or module page is missing')
    review=json.loads((ROOT/'tools/ford-documentation.json').read_text())
    from bs4 import BeautifulSoup
    for name,doc in review['procedures'].items():
        html=BeautifulSoup((OUTPUT/'proc'/f'{name.lower()}.html').read_text(encoding='utf-8'),'html.parser')
        for section in html.select('#text > section'):
            if 'Source Code' in section.get_text(): section.decompose()
        first=doc.splitlines()[0]
        # Rendered Markdown removes inline-code markers.
        if first.replace('`','') not in html.get_text():
            raise ValueError('Missing procedure description: '+name)
        if name in ('IPMPAR','SHELL','STOD') and not any('Meaning' in t.get_text() for t in html.find_all('th')):
            raise ValueError('Missing argument/result table: '+name)
    spmpar=BeautifulSoup((OUTPUT/'proc/spmpar.html').read_text(encoding='utf-8'),'html.parser')
    if not any('spmpar(1) = b**(1 - m)' in node.get_text() for node in spmpar.select('pre')):
        raise ValueError('Machine-model formulas were not preserved as code')
    for name,target in [('spmpar','ipmpar'),('cbrt','dcbrt'),('stod','sfode')]:
        html=BeautifulSoup((OUTPUT/'proc'/f'{name}.html').read_text(encoding='utf-8'),'html.parser')
        links=[a.get('href','').replace('\\','/').split('#',1)[0] for a in html.find_all('a')]
        if not any(link.endswith('/'+target+'.html') or link==target+'.html' for link in links):
            raise ValueError('Missing resolved FORD procedure link: '+name+' -> '+target)
    metadata={'source_sha256':hashlib.sha256(source).hexdigest(),
              'project_sha256':hashlib.sha256((ROOT/'ford.md').read_bytes()).hexdigest(),
              'documentation_sha256':hashlib.sha256((ROOT/'tools/ford-documentation.json').read_bytes()).hexdigest(),
              'requirements_sha256':hashlib.sha256((ROOT/'requirements-docs.txt').read_bytes()).hexdigest(),
              'procedures':len(expected),'reviewed_prologues':len(review['procedures'])}
    print(f'FORD: {len(expected)} procedure pages; {len(review["procedures"])} reviewed prologues, tables, formulas and links checked.',flush=True)
    return metadata


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='Check an existing build without rebuilding')
    args=parser.parse_args()
    for path in (STAGE,OUTPUT):
        if not path.resolve().is_relative_to(ROOT) or not path.resolve().is_relative_to((ROOT/'reports').resolve()):
            raise ValueError('FORD build path must remain inside this project reports directory')
    if not args.check:
        if OUTPUT.exists() and any(OUTPUT.iterdir()) and not (OUTPUT/OWNER).is_file():
            raise ValueError('Refusing to replace an output directory without the NSWC ownership marker')
        STAGE.mkdir(parents=True,exist_ok=True)
        if any(p.name!='nswc_mod.f90' for p in STAGE.iterdir()):
            raise ValueError('Unexpected files in the single-source FORD staging directory')
        (STAGE/'nswc_mod.f90').write_bytes((ROOT/'nswc_mod.f90').read_bytes())
        flags=['-S'] if sys.flags.no_site else []
        subprocess.run([sys.executable,*flags,'-m','ford',str(ROOT/'ford.md'),'--src_dir',str(STAGE),'--output_dir',str(OUTPUT)],cwd=ROOT,check=True)
        (OUTPUT/OWNER).write_text('Generated by tools/build_ford.py\n',encoding='ascii')
        metadata=check_site()
        (OUTPUT/'nswc-build.json').write_text(json.dumps(metadata,indent=2)+'\n',encoding='ascii')
    else:
        if check_site()!=json.loads((OUTPUT/'nswc-build.json').read_text()):
            raise ValueError('FORD build metadata is stale')

if __name__=='__main__':main()
