"""Generate the fpm module mirror and module-based numerical drivers.

Package builds use committed Fortran files and need neither Python nor the
external-procedure sources. Original drivers retain all maintenance diagnostics.
"""
import argparse
from pathlib import Path
import re
from fortran_procedures import procedure_spans
from validate_interfaces import module_caller
from validate_sources import test_programs
ROOT=Path(__file__).resolve().parents[1]
MARKER='! Generated by tools/generate_fpm.py; edit the original driver instead.\n'


def driver(text,names,periodic=False):
    text=module_caller(text,names).replace('use nswc_interfaces,','use nswc_mod,')
    text=re.sub(r'^! Adapted from C:/fortran/(.*)$',r'! Adapted from \1',text,flags=re.M)
    text=re.sub(r'^! Standalone legacy-interface driver:.*\n','',text,flags=re.M)
    if periodic:
        removals=[
            '   integer :: npp, k, nm, ncmplx, ik\n',
            '   real :: eps, cnv\n',
            '   common /cblkt/ npp, k, eps, cnv, nm, ncmplx, ik\n',
            '            if (ncmplx /= mode) stop 2\n']
        for original in removals:
            if text.count(original)!=1:raise ValueError('Periodic driver needs a new public-state adaptation: '+original)
            text=text.replace(original,'')
        text='! Private-state branch diagnostics remain in tests/fortran/test_blktri_periodic.f90.\n'+text
    if re.search(r'\b(?:nswc_interfaces|nswc_state_\w+|common\s*/)',text,re.I):
        raise ValueError('Package driver retained an interface module or private storage dependency')
    return text


def outputs(root=ROOT,module=None):
    module=(root/'nswc_mod.f90').read_text(encoding='ascii') if module is None else module
    names={n for n,_,_ in procedure_spans(module)}
    result={root/'src/nswc_mod.f90':module}
    programs=[*test_programs(root),root/'tests/module/test_intrinsic_aliases.f90']
    for path in programs:
        text=driver(path.read_text(encoding='ascii'),names,periodic=path.stem=='test_blktri_periodic')
        result[root/'test'/path.name]=MARKER+'! Original: '+path.relative_to(root).as_posix()+'\n'+text
    path=root/'tests/purity/test_pure_elemental.f90'
    text=path.read_text(encoding='ascii')
    if not text.count('use nswc_interfaces,'):raise ValueError('Pure/elemental driver import needs review')
    result[root/'test'/path.name]=MARKER+'! Original: '+path.relative_to(root).as_posix()+'\n'+text.replace('use nswc_interfaces,','use nswc_mod,')
    return result


def obsolete(root,expected):
    return [path for path in (root/'test').glob('*.f90')
            if path not in expected and path.read_bytes().splitlines()[:1]==[MARKER.rstrip('\n').encode('ascii')]]


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true');args=parser.parse_args()
    expected=outputs();stale=obsolete(ROOT,expected)
    changed=[p for p,text in expected.items() if not p.exists() or p.read_bytes()!=text.encode('ascii')]
    if args.check:
        for path in changed+stale:print('Stale:',path.relative_to(ROOT))
        print(f'Checked fpm module mirror and {len(expected)-1} generated drivers.')
        return int(bool(changed or stale))
    for path in changed:
        path.parent.mkdir(parents=True,exist_ok=True)
        path.write_text(expected[path],encoding='ascii',newline='\n')
    for path in stale:path.unlink()
    print(f'Generated fpm module mirror and {len(expected)-1} module-based drivers.')
    return 0

if __name__=='__main__':raise SystemExit(main())
